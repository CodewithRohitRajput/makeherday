export type ThemeGroup = "soft" | "dark" | "bright";

export interface GiftTheme {
  id: string;
  name: string;
  group: ThemeGroup;
  /** Light text on a dark card. */
  dark: boolean;
  /** Card background. */
  background: string;
  ink: string;
  muted: string;
  accent: string;
  /** Hairline borders and dividers on the card. */
  line: string;
  /** Wax seal colour and the emblem drawn on it. */
  seal: string;
  sealInk: string;
  /** Backdrop of the page the gift is opened on. */
  page: { base: string; glow: string };
  /** Swatch shown in the theme picker. */
  swatch: string;
}

